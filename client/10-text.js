/** The text of `key` in English, with `{name}` filled in: what is shown when the host's locale service cannot answer. */
const FALLBACK = (key, params) => (en[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => String(params?.[name] ?? ''))

/**
 * The translator of a context: the host's locale service where it answers, English otherwise. A key the service does
 * not know comes back as the key itself, which is never shown.
 */
function translator(ctx) {
  let bound
  try {
    bound = ctx.locale?.bind?.('awr')
  } catch {
    bound = undefined
  }
  if (typeof bound !== 'function') return FALLBACK
  return (key, params) => {
    let text
    try {
      text = bound(key, params)
    } catch {
      text = undefined
    }
    return typeof text === 'string' && text !== key ? text : FALLBACK(key, params)
  }
}
